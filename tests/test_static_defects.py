"""Focused tests for the static-analysis defects and the quality ratchets."""

from __future__ import annotations

import ast
import importlib.util
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


def _load_ratchet():
    path = ROOT / "scripts" / "check_mypy_ratchet.py"
    spec = importlib.util.spec_from_file_location("check_mypy_ratchet", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _cmap():
    from ctxpack.modules.codebase import CodebaseMap, ModuleInfo

    return CodebaseMap(
        modules=[
            ModuleInfo(
                path="pkg/api.py",
                routes=["GET /health"],
                functions=["health"],
            )
        ],
        total_files=1,
        total_lines=12,
        frameworks=["FastAPI"],
        architecture="service",
    )


def test_build_hydration_tool_schema_defined_once_and_canonical():
    import ctxpack.core.hydration_protocol as proto

    source = Path(proto.__file__).read_text(encoding="utf-8")
    tree = ast.parse(source)
    names = [
        node.name for node in tree.body
        if isinstance(node, ast.FunctionDef)
        and node.name == "build_hydration_tool_schema"
    ]
    assert names == ["build_hydration_tool_schema"]
    schema = proto.build_hydration_tool_schema()
    assert schema["name"] == "ctx/hydrate"
    assert schema["parameters"]["type"] == "object"
    assert schema["parameters"]["required"] == ["section"]
    assert "section" in schema["parameters"]["properties"]


def test_export_claude_md_preserves_and_remerges_user_content():
    from ctxpack.modules.codebase import export_claude_md

    cmap = _cmap()
    existing = "# Team rules\n\nDo not force-push.\n"
    once = export_claude_md(
        cmap, existing_claude_md=existing, merge_existing=True)
    assert once.startswith("# Team rules\n")
    assert "Do not force-push." in once
    assert "## Architecture" in once
    assert "service" in once
    assert "<!-- ctxpack:codebase-map:begin -->" in once
    assert once.count("<!-- ctxpack:codebase-map:begin -->") == 1

    twice = export_claude_md(
        cmap, existing_claude_md=once, merge_existing=True)
    assert twice == once
    assert twice.count("Do not force-push.") == 1

    bare = export_claude_md(cmap)
    assert bare.startswith("# Codebase Map (auto-generated by ctxpack")
    assert "Do not force-push." not in bare
    assert "<!-- ctxpack:codebase-map:begin -->" not in bare
    assert export_claude_md(cmap, existing_claude_md=bare) == bare

    # max_lines caps the generated block only. User text, including the
    # negation, is not truncated away.
    short = export_claude_md(
        cmap, existing_claude_md=existing, max_lines=4, merge_existing=True)
    assert "Do not force-push." in short
    assert "*(truncated to fit context budget)*" in short


def test_export_claude_md_standalone_map_does_not_copy_parent_claude_md():
    """The CLI always passes CLAUDE.md, including when the output is the
    supplementary map. That parent imports the map; copying it in would
    make `@.claude/codebase-map.md` include itself."""
    from ctxpack.modules.codebase import export_claude_md

    parent = (
        "# Team rules\n\nDo not force-push.\n\n"
        "@.claude/codebase-map.md\n"
    )
    md = export_claude_md(_cmap(), existing_claude_md=parent)
    assert "Do not force-push." not in md
    assert md.startswith("# Codebase Map (auto-generated by ctxpack")
    assert md.count("@.claude/codebase-map.md") == 1
    assert "<!-- ctxpack:codebase-map:begin -->" not in md


def test_export_claude_md_malformed_markers_are_not_rewritten():
    from ctxpack.modules.codebase import (
        _CODEBASE_MAP_BEGIN,
        _CODEBASE_MAP_END,
        export_claude_md,
    )

    cmap = _cmap()
    reversed_markers = (
        f"keep this\n{_CODEBASE_MAP_END}\n"
        f"generated\n{_CODEBASE_MAP_BEGIN}\n"
    )
    missing_end = f"keep this\n{_CODEBASE_MAP_BEGIN}\ngenerated with no end\n"
    missing_begin = f"keep this\n{_CODEBASE_MAP_END}\n"
    for existing in (reversed_markers, missing_end, missing_begin):
        with pytest.raises(ValueError, match="malformed"):
            export_claude_md(
                cmap, existing_claude_md=existing, merge_existing=True)


def test_annotate_authority_returns_the_journal(tmp_path):
    from ctxpack.agent.session_reader import _annotate_authority
    from ctxpack.core.factid import OWNER_APPROVAL_UNAVAILABLE

    matches = [{
        "fields": [
            {"key": "FACT-ID", "value": "abc123"},
            {"key": "SOURCE-ROLE", "value": "assistant"},
        ],
    }]
    journal = _annotate_authority(matches, str(tmp_path))
    assert isinstance(journal, dict)
    assert journal["degraded"] is False
    assert journal["state"] == {}
    assert journal["malformed_rows"] == 0
    assert matches[0]["authority"] == "agent_candidate"
    assert matches[0]["owner_approval"] == OWNER_APPROVAL_UNAVAILABLE

    # Doc-only callers pass an empty ledger dir. The return is still the
    # journal, and it is a real zero rather than None.
    empty = _annotate_authority(matches, "")
    assert empty["degraded"] is False
    assert empty["state"] == {}


