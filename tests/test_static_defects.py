def test_mypy_ratchet_fails_closed_without_a_summary():
    ratchet = _load_ratchet()
    missing = ratchet.assess("/usr/bin/python: No module named mypy\n", 1, baseline=56)
    assert missing == 1
    empty = ratchet.assess("", 1, baseline=56)
    assert empty == 1


def test_mypy_ratchet_accepts_a_real_summary_inside_the_baseline():
    ratchet = _load_ratchet()
    text = (
        "ctxpack/a.py:1: error: boom  [misc]\n"
        "Found 1 error in 1 file (checked 2 source files)\n"
    )
    assert ratchet.assess(text, 1, baseline=56) == 0
    success = "Success: no issues found in 2 source files\n"
    assert ratchet.assess(success, 0, baseline=56) == 0


def test_mypy_ratchet_rejects_a_summary_that_does_not_match_the_lines():
    ratchet = _load_ratchet()
    text = (
        "ctxpack/a.py:1: error: boom  [misc]\n"
        "Found 4 errors in 1 file (checked 2 source files)\n"
    )
    assert ratchet.assess(text, 1, baseline=56) == 1
