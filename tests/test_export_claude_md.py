"""export_claude_md keeps hand-written CLAUDE.md text and refreshes the map."""
from __future__ import annotations

from ctxpack.modules.codebase import CodebaseMap, ModuleInfo, export_claude_md

_HEADER = "# Codebase Map (auto-generated by ctxpack — DO NOT EDIT)"
_END = "<!-- ctxpack:codebase-map:end -->"


def _cmap() -> CodebaseMap:
    return CodebaseMap(
        modules=[
            ModuleInfo(
                path="app/main.py",
                functions=["health"],
                routes=["GET /health"],
            )
        ],
        total_files=1,
        total_lines=12,
        frameworks=["FastAPI"],
        architecture="service",
    )


def test_generated_map_without_existing_content():
    md = export_claude_md(_cmap())
    assert md.startswith(_HEADER)
    assert "## Architecture" in md
    assert md.rstrip().endswith(_END)
    assert md.count(_HEADER) == 1


def test_existing_hand_written_content_is_preserved():
    existing = "# Team rules\n\nDo not touch auth.\n"
    md = export_claude_md(_cmap(), existing_claude_md=existing)
    assert md.startswith("# Team rules")
    assert "Do not touch auth." in md
    assert _HEADER in md
    assert "## Architecture" in md
    # The hand-written section stays above the generated map.
    assert md.index("Do not touch auth.") < md.index(_HEADER)


def test_reexport_does_not_duplicate_hand_written_or_generated_blocks():
    existing = "# Team rules\n\nDo not touch auth.\n"
    once = export_claude_md(_cmap(), existing_claude_md=existing)
    twice = export_claude_md(_cmap(), existing_claude_md=once)
    assert twice.count("# Team rules") == 1
    assert twice.count("Do not touch auth.") == 1
    assert twice.count(_HEADER) == 1
    assert twice.count(_END) == 1
    assert "## Architecture" in twice


def test_notes_after_the_generated_block_survive_reexport():
    once = export_claude_md(
        _cmap(), existing_claude_md="# Team rules\n\nDo not touch auth.\n")
    with_notes = once + "\n\n## Local notes\n\nAfter the map.\n"
    again = export_claude_md(_cmap(), existing_claude_md=with_notes)
    assert "After the map." in again
    assert again.count("## Local notes") == 1
    assert again.count(_HEADER) == 1
    assert again.index(_END) < again.index("## Local notes")


def test_max_lines_does_not_drop_hand_written_text():
    existing = "# Team rules\n\n" + ("Do not touch auth.\n" * 30)
    md = export_claude_md(_cmap(), existing_claude_md=existing, max_lines=8)
    assert md.startswith("# Team rules")
    assert md.count("Do not touch auth.") == 30
    assert _HEADER in md
    assert _END in md
